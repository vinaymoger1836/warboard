"""Base proposal (doc 11 §2.5): air and naval bases per nation → content/bases/<nation>/.

Reads a built theatre pack (work/<pack>/nations.npz) and content/world/places.yaml.

- Air base: flat open land (class open or desert, slope at most AIR_MAX_SLOPE_DEG over
  the cell and its neighbours, so a runway fits), not built-up, inside the nation and
  at least AIR_BORDER_KM from its land borders. The first is near the capital; the rest
  are spread out (each as far as possible from those already chosen).
- Naval base: a coast cell whose neighbouring sea is the nation's own, sheltered (about
  NAVAL_SHELTER of the water around it enclosed by land: a bay or gulf), at least
  NAVAL_BORDER_KM from land borders, spread out the same way.
- Counts: 3–6 air bases and 1–3 naval bases per nation, scaled by land area and coast.
  Small nations get fewer when nothing more fits the spacing.
- Names: the nearest city within NAME_CITY_KM, else a generated name (geodata/names.yaml).

Files start with GENERATED_MARK and are rewritten on a re-run. Remove the mark to keep a
base as edited: it is never touched again and counts towards its nation's bases.
Sizes are placeholders until the admin app (P8) curates them.
"""

from __future__ import annotations

import math
import re
import unicodedata

import h3.api.basic_int as h3
import numpy as np
import yaml

from . import formats
from .borders import Namer, hops_from, load_theatre
from .common import ROOT, log

GENERATED_MARK = "# Generated by `geodata bases`"
AIR_MAX_SLOPE_DEG = 2.0
AIR_MAX_ELEV_M = 1200.0
AIR_BORDER_KM = 40.0
NAVAL_BORDER_KM = 25.0
NAVAL_SHELTER = 0.6
NAVAL_SHELTER_RANGE = (0.4, 0.85)
NAVAL_DISK = 5  # rings around the coast cell for the shelter share (about 12 km at res 7)
NAME_CITY_KM = 60.0
LAND_CELLS_PER_AIR_BASE = 30_000
COAST_CELLS_PER_NAVAL_BASE = 1_000
AIR_SIZES = [(3000.0, 48), (2600.0, 30)]  # (runway m, aircraft): main base, others
NAVAL_BERTHS = [10, 6]
CELL_KM = 2.43  # centre spacing of res-7 cells


def _slug(text: str) -> str:
    text = unicodedata.normalize("NFKD", text.replace("ø", "o").replace("Ø", "O")).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def _dist_km(lat1, lon1, lat2, lon2):
    p1, p2 = np.radians(lat1), np.radians(lat2)
    dl = np.radians(np.asarray(lon2) - lon1)
    a = np.sin((p2 - p1) / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * 6371.0088 * np.arcsin(np.sqrt(np.minimum(a, 1.0)))


def _spread(th, cand: np.ndarray, first_near: tuple[float, float] | None, taken: list[tuple[float, float]], want: int, spacing_km: float) -> list[int]:
    """Farthest-point picks from candidate cell indexes, at least `spacing_km` apart."""
    out: list[int] = []
    pts = list(taken)
    if len(cand) == 0:
        return out
    lat, lon = th.lat[cand], th.lon[cand]
    if first_near is not None and not pts:
        d = _dist_km(first_near[0], first_near[1], lat, lon)
        # Near the capital but not inside it.
        score = np.abs(d - 30.0)
        i = int(np.lexsort((cand, score))[0])
        out.append(int(cand[i]))
        pts.append((float(lat[i]), float(lon[i])))
    while len(out) < want:
        if pts:
            dmin = np.min(np.stack([_dist_km(a, b, lat, lon) for a, b in pts]), axis=0)
        else:
            dmin = np.full(len(cand), np.inf)
        i = int(np.lexsort((cand, -dmin))[0])
        if dmin[i] < spacing_km:
            break
        out.append(int(cand[i]))
        pts.append((float(lat[i]), float(lon[i])))
    return out


def _existing() -> tuple[dict[str, list[dict]], list]:
    """Hand-kept bases per nation, and the generated files to replace."""
    kept: dict[str, list[dict]] = {}
    generated = []
    root = ROOT / "content" / "bases"
    for f in sorted(root.glob("*/*.yaml")):
        text = f.read_text(encoding="utf-8")
        if text.startswith(GENERATED_MARK):
            generated.append(f)
            continue
        data = yaml.safe_load(text)
        kept.setdefault(data["nation"], []).append(data)
    return kept, generated


def _yaml(base: dict) -> str:
    lines = [
        GENERATED_MARK + " (doc 11 §2.5); remove this line to keep edits.",
        f"id: {base['id']}",
        "kind: base",
        f"name: {base['name']}",
        f"base_type: {base['base_type']}",
        f"nation: {base['nation']}",
        f"lat_deg: {base['lat_deg']:.4f}",
        f"lon_deg: {base['lon_deg']:.4f}",
        f"elevation_m: {base['elevation_m']:.0f}",
    ]
    if base.get("runway_length_m"):
        lines.append(f"runway_length_m: {base['runway_length_m']:.0f}")
    if base.get("aircraft_capacity"):
        lines.append(f"aircraft_capacity: {base['aircraft_capacity']}")
    if base.get("ship_berths"):
        lines.append(f"ship_berths: {base['ship_berths']}")
    lines.append(f"design: {{ note: \"{base['note']}\" }}")
    return "\n".join(lines) + "\n"


def build(pack_id: str = "europe") -> None:
    th = load_theatre(pack_id)
    places = yaml.safe_load((ROOT / "content" / "world" / "places.yaml").read_text(encoding="utf-8"))["places"]
    kept, generated = _existing()
    for f in generated:
        f.unlink()
    namer = Namer(th.world.seed + 1)
    namer.used |= {p["name"] for p in places}
    open_cls = np.isin(th.cls, [formats.CLASS["open"], formats.CLASS["desert"]])
    written = 0
    for i, code in enumerate(th.codes):
        own = th.landlike & (th.owner == i)
        if not own.any():
            continue
        others = th.landlike & (th.owner != i)
        nb = th.nbr
        valid = nb >= 0
        nb0 = np.maximum(nb, 0)
        edge = own & np.any(valid & others[nb0], axis=1)
        hops = hops_from(nb, edge, own)
        border_km = hops * CELL_KM
        cities = [p for p in places if p.get("nation") == code and p["kind"] in ("capital", "city")]
        capital = next(((p["at"][1], p["at"][0]) for p in cities if p["kind"] == "capital"), None)
        land_km2 = float(own.sum()) * 5.16
        spacing = min(150.0, max(30.0, math.sqrt(land_km2) / 3.0))

        mine = kept.get(code, [])
        air_kept = [(b["lat_deg"], b["lon_deg"]) for b in mine if b["base_type"] in ("air_base", "air_base_and_port")]
        sea_kept = [(b["lat_deg"], b["lon_deg"]) for b in mine if b["base_type"] in ("port", "air_base_and_port")]

        # Air bases.
        flat_nb = np.all(~valid | (own[nb0] & (th.slope[nb0] <= AIR_MAX_SLOPE_DEG + 1.0) & open_cls[nb0]), axis=1)
        cand = own & open_cls & (th.slope <= AIR_MAX_SLOPE_DEG) & flat_nb
        cand &= (th.flags & formats.FLAG_URBAN) == 0
        cand &= th.elev <= AIR_MAX_ELEV_M
        cand &= border_km >= AIR_BORDER_KM
        want_air = max(3, min(6, int(own.sum()) // LAND_CELLS_PER_AIR_BASE + 2)) - len(air_kept)
        air = _spread(th, np.flatnonzero(cand), capital, air_kept, max(0, want_air), spacing)

        # Naval bases.
        sea_own = th.sea & (th.owner == i)
        coast = own & np.any(valid & sea_own[nb0], axis=1) & (border_km >= NAVAL_BORDER_KM) & (th.elev <= 50)
        coast_idx = np.flatnonzero(coast)
        shelter = np.zeros(len(coast_idx))
        for k, c in enumerate(coast_idx.tolist()):
            disk = np.array(h3.grid_disk(int(th.cells[c]), NAVAL_DISK), dtype=np.uint64)
            pos = np.minimum(np.searchsorted(th.cells, disk), len(th.cells) - 1)
            inside = th.cells[pos] == disk
            shelter[k] = float(th.landlike[pos[inside]].mean()) if inside.any() else 0.0
        lo, hi = NAVAL_SHELTER_RANGE
        good = (shelter >= lo) & (shelter <= hi)
        naval_cand = coast_idx[good]
        want_sea = max(1, min(3, len(coast_idx) // COAST_CELLS_PER_NAVAL_BASE + 1)) - len(sea_kept)
        # Most sheltered first among well-spread sites: pick from the best half.
        if len(naval_cand):
            sh = shelter[good]
            order = np.lexsort((naval_cand, np.abs(sh - NAVAL_SHELTER)))
            naval_cand = naval_cand[order[: max(1, len(order) // 2)]]
        naval = _spread(th, naval_cand, capital, sea_kept, max(0, want_sea), max(spacing, 60.0))

        named: set[tuple[str, str]] = {(b["name"].rsplit(" ", 2)[0], "air" if b["base_type"] == "air_base" else "naval") for b in mine}
        out_dir = ROOT / "content" / "bases" / code
        out_dir.mkdir(parents=True, exist_ok=True)
        for kind, picks in (("air", air), ("naval", naval)):
            for rank, c in enumerate(picks):
                la, lo_ = float(th.lat[c]), float(th.lon[c])
                near = sorted(
                    (float(_dist_km(la, lo_, p["at"][1], p["at"][0])), p["name"]) for p in cities
                )
                town = near[0][1] if near and near[0][0] <= NAME_CITY_KM else None
                if town is None or (town, kind) in named:
                    town = namer.name(code, "base", kind, rank)
                named.add((town, kind))
                label = "Air Base" if kind == "air" else "Naval Base"
                base = {
                    "id": f"{code}-{_slug(town)}-{kind}",
                    "name": f"{town} {label}",
                    "base_type": "air_base" if kind == "air" else "port",
                    "nation": code,
                    "lat_deg": la,
                    "lon_deg": lo_,
                    "elevation_m": max(0.0, float(th.elev[c])),
                }
                if kind == "air":
                    runway, capacity = AIR_SIZES[0 if rank == 0 else 1]
                    base["runway_length_m"] = runway
                    base["aircraft_capacity"] = capacity
                    base["note"] = "Proposed on flat open land away from borders; runway and capacity are placeholders"
                else:
                    base["ship_berths"] = NAVAL_BERTHS[0 if rank == 0 else 1]
                    base["note"] = "Proposed on a sheltered coast facing own waters; berths are placeholders"
                path = out_dir / f"{base['id']}.yaml"
                path.write_text(_yaml(base), encoding="utf-8")
                written += 1
        log(f"bases: {code}: {len(air)} air, {len(naval)} naval ({len(mine)} kept)")
    log(f"bases: wrote {written} files")
