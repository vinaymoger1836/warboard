"""Bases: OurAirports airfields + curated naval ports → content/bases/*.yaml (doc 05 §1, §7).

Airfields are kept when they lie inside the `europe` pack extent, belong to a country that
exists in content/countries/, are open, and are either military by name or keywords, or
have a hard runway of at least CIVIL_MIN_RUNWAY_M. Hand-written base files are never
touched: an airfield whose ICAO code already appears in content is skipped, and only files
that start with GENERATED_MARK are rewritten on a re-run.
"""

from __future__ import annotations

import csv
import re
import unicodedata
from pathlib import Path

import yaml

from . import sources
from .common import GEODATA, ROOT, load_packs, load_sources, log

GENERATED_MARK = "# Generated by `geodata bases`"
CIVIL_MIN_RUNWAY_M = 2400.0
MILITARY_MIN_RUNWAY_M = 1200.0
# Aircraft that can be stationed: a placeholder until P8 curates bases (listed as an estimate).
CAPACITY = {"military": 24, "civil": 12}
FT = 0.3048
MILITARY = re.compile(r"(?i)\b(air ?base|air force|military|naval air|aviation base|afb|ab)\b")
HARD = re.compile(r"(?i)(asp|con|pem|bit|tarmac|paved|hard)")


# Letters NFKD does not split into a base letter and a mark.
TRANSLIT = str.maketrans({"ł": "l", "Ł": "L", "ø": "o", "Ø": "O", "đ": "d", "Đ": "D", "ß": "ss", "æ": "ae", "Æ": "AE", "œ": "oe", "ı": "i"})


def _slug(text: str) -> str:
    text = unicodedata.normalize("NFKD", text.translate(TRANSLIT)).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return re.sub(r"-{2,}", "-", s)[:48].strip("-")


def _content_countries() -> dict[str, str]:
    out = {}
    for f in sorted((ROOT / "content" / "countries").glob("*.yaml")):
        data = yaml.safe_load(f.read_text(encoding="utf-8"))
        out[data["iso2"].upper()] = data["id"]
    return out


def _existing() -> tuple[set[str], set[str], set[Path]]:
    """ICAO codes and ids of hand-written bases, and paths of generated files."""
    icaos, ids, generated = set(), set(), set()
    for f in sorted((ROOT / "content" / "bases").glob("*.yaml")):
        text = f.read_text(encoding="utf-8")
        if text.startswith(GENERATED_MARK):
            generated.add(f)
            continue
        data = yaml.safe_load(text)
        ids.add(data["id"])
        if data.get("icao"):
            icaos.add(str(data["icao"]).upper())
    return icaos, ids, generated


def _runways(path: Path) -> dict[str, float]:
    """Longest open hard runway per airport ident, metres."""
    best: dict[str, float] = {}
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["closed"] == "1" or not r["length_ft"] or not HARD.search(r["surface"] or ""):
                continue
            m = float(r["length_ft"]) * FT
            if m > best.get(r["airport_ident"], 0.0):
                best[r["airport_ident"]] = m
    return best


def _yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _airfield_yaml(r: dict, country: str, runway_m: float, military: bool, base_id: str, accessed: str) -> str:
    icao = (r["icao_code"] or r["gps_code"] or "").upper()
    lines = [
        f"{GENERATED_MARK} from OurAirports; curate by removing this first line.",
        f"id: {base_id}",
        "kind: base",
        f"name: {_yaml_str(r['name'])}",
        "base_type: air_base",
        f"country: {country}",
    ]
    if re.fullmatch(r"[A-Z]{4}", icao):
        lines.append(f"icao: {icao}")
    lines += [
        f"lat_deg: {float(r['latitude_deg']):.4f}",
        f"lon_deg: {float(r['longitude_deg']):.4f}",
    ]
    if r["elevation_ft"]:
        lines.append(f"elevation_m: {float(r['elevation_ft']) * FT:.1f}")
    lines += [
        f"runway_length_m: {round(runway_m)}",
        f"aircraft_capacity: {CAPACITY['military' if military else 'civil']}",
        "provenance:",
        "  confidence: medium",
        "  notes: >-",
        f"    Imported from OurAirports ({'military by name or keywords' if military else 'civil, hard runway at least 2,400 m'}).",
        "    Position, elevation and longest hard runway are from the source.",
        "  estimates:",
        "    - aircraft_capacity",
        "  sources:",
        f"    - {{ title: {_yaml_str('OurAirports: ' + r['name'] + ' (' + r['ident'] + ')')}, "
        f"url: \"https://ourairports.com/airports/{r['ident']}/\", accessed: {accessed} }}",
    ]
    return "\n".join(lines) + "\n"


def _port_yaml(p: dict, accessed: str) -> str:
    where = "the town's" if p["coords"] == "town" else "the page's"
    lines = [
        f"{GENERATED_MARK} from geodata/curated/ports.yaml; curate by removing this first line.",
        f"id: {p['id']}",
        "kind: base",
        f"name: {_yaml_str(p['name'])}",
        "base_type: port",
        f"country: {p['country']}",
        f"lat_deg: {p['lat_deg']}",
        f"lon_deg: {p['lon_deg']}",
        f"ship_berths: {p['ship_berths']}",
        "provenance:",
        "  confidence: medium",
        "  notes: >-",
        f"    Naval base from the curated list. Coordinates are {where}.",
        "  estimates:",
        "    - ship_berths",
        "  sources:",
        f"    - {{ title: {_yaml_str(p['source']['title'])}, url: \"{p['source']['url']}\", accessed: {accessed} }}",
    ]
    return "\n".join(lines) + "\n"


def build() -> None:
    accessed = load_sources()["ourairports"]["accessed"]
    w, s, e, n = load_packs()["europe"].extent
    countries = _content_countries()
    icaos, ids, generated = _existing()
    airports, runways_csv = sources.ourairports()
    runways = _runways(runways_csv)

    files: dict[str, str] = {}
    skipped_dupe = 0
    with open(airports, newline="", encoding="utf-8") as f:
        rows = sorted(csv.DictReader(f), key=lambda r: r["ident"])
    for r in rows:
        if r["type"] not in ("large_airport", "medium_airport", "small_airport"):
            continue
        country = countries.get(r["iso_country"])
        lat, lon = float(r["latitude_deg"]), float(r["longitude_deg"])
        if country is None or not (w <= lon <= e and s <= lat <= n):
            continue
        runway = runways.get(r["ident"], 0.0)
        military = bool(MILITARY.search(r["name"]) or MILITARY.search(r["keywords"] or ""))
        if not ((military and runway >= MILITARY_MIN_RUNWAY_M) or runway >= CIVIL_MIN_RUNWAY_M):
            continue
        icao = (r["icao_code"] or r["gps_code"] or "").upper()
        if icao in icaos:
            skipped_dupe += 1
            continue
        base_id = f"{_slug(r['name'])}-{r['ident'].lower()}"
        base_id = re.sub(r"[^a-z0-9-]", "", base_id)
        if base_id in ids or base_id in files:
            continue
        files[base_id] = _airfield_yaml(r, country, runway, military, base_id, accessed)

    curated = yaml.safe_load((GEODATA / "curated" / "ports.yaml").read_text(encoding="utf-8"))
    for p in curated["ports"]:
        if p["id"] in ids or p["country"] not in countries.values():
            continue
        files[p["id"]] = _port_yaml(p, str(curated["accessed"]))

    out_dir = ROOT / "content" / "bases"
    for old in generated:
        if old.stem not in files:
            old.unlink()
    for base_id, text in sorted(files.items()):
        (out_dir / f"{base_id}.yaml").write_text(text, encoding="utf-8", newline="\n")
    mil = sum("military by name" in t for t in files.values())
    ports = sum("base_type: port" in t for t in files.values())
    log(
        f"bases: wrote {len(files)} files ({mil} military airfields, {len(files) - mil - ports} civil airfields, "
        f"{ports} ports); skipped {skipped_dupe} already in content"
    )
