//! JSON Schema of the source format, for the admin's generated forms.
//!
//! The output maps each kind to the schema of one entry file. The meta keys of
//! [`EntryMeta`] are merged into every kind's properties, with `kind` fixed to
//! that kind.

use crate::source::{
    Base, Countermeasure, Country, Datalink, Doctrine, EntryMeta, EwSuite, Inventory, Kind,
    Loadout, Manifest, Platform, Realism, Sensor, System, Weapon,
};
use schemars::{JsonSchema, schema_for};
use serde_json::{Map, Value, json};

fn kind_schema<T: JsonSchema>(kind: Kind, meta: &Value) -> Value {
    let mut schema = schema_for!(T).to_value();
    if let Some(props) = schema.get_mut("properties").and_then(Value::as_object_mut) {
        if let Some(meta_props) = meta.get("properties").and_then(Value::as_object) {
            for (k, v) in meta_props {
                props.insert(k.clone(), v.clone());
            }
        }
        props.insert("kind".into(), json!({ "const": kind.as_str() }));
    }
    if let Some(req) = schema.get_mut("required").and_then(Value::as_array_mut) {
        req.push(json!("kind"));
    }
    // The meta schema's own definitions (e.g. `Kind`) are not needed: `kind`
    // is a constant here.
    schema
}

/// `{ "$comment": …, "manifest": {…}, "kinds": { "platform": {…}, … } }`.
pub fn content_schema() -> Value {
    let meta = schema_for!(EntryMeta).to_value();
    let mut kinds = Map::new();
    for kind in Kind::ALL {
        let s = match kind {
            Kind::Country => kind_schema::<Country>(kind, &meta),
            Kind::Platform => kind_schema::<Platform>(kind, &meta),
            Kind::System => kind_schema::<System>(kind, &meta),
            Kind::Sensor => kind_schema::<Sensor>(kind, &meta),
            Kind::Weapon => kind_schema::<Weapon>(kind, &meta),
            Kind::EwSuite => kind_schema::<EwSuite>(kind, &meta),
            Kind::Countermeasure => kind_schema::<Countermeasure>(kind, &meta),
            Kind::Datalink => kind_schema::<Datalink>(kind, &meta),
            Kind::Loadout => kind_schema::<Loadout>(kind, &meta),
            Kind::Base => kind_schema::<Base>(kind, &meta),
            Kind::Inventory => kind_schema::<Inventory>(kind, &meta),
            Kind::Doctrine => kind_schema::<Doctrine>(kind, &meta),
            Kind::Realism => kind_schema::<Realism>(kind, &meta),
        };
        kinds.insert(kind.as_str().into(), s);
    }
    json!({
        "$comment": "Generated by `wb content schema` from wb-content. Do not edit.",
        "schema_version": crate::pack::SCHEMA_VERSION,
        "manifest": schema_for!(Manifest).to_value(),
        "kinds": kinds,
    })
}
